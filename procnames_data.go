// transientConsoleUtilities are short-lived system helper utilities that must NEVER receive Eco Mode.
var transientConsoleUtilities = map[string]struct{}{
	"tasklist.exe":   {},
	"conhost.exe":    {},
	"cmd.exe":        {},
	"powershell.exe": {},
	"pwsh.exe":       {},
	"findstr.exe":    {},
	"dxdiag.exe":     {},
	"wmic.exe":       {},
	"cscript.exe":    {},
	"wscript.exe":    {},
}

// isTransientConsoleUtility returns true for short-lived console commands.
func isTransientConsoleUtility(name string) bool {
	base := strings.ToLower(filepath.Base(strings.TrimSpace(name)))
	_, ok := transientConsoleUtilities[base]
	return ok
}

