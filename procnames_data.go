// friendlyProcessName returns a human-readable explanation in Russian (default fallback).
func friendlyProcessName(name string) string {
	return friendlyProcessNameLang(name, "ru")
}

// friendlyProcessNameLang returns a human-readable explanation in the requested language.
func friendlyProcessNameLang(name string, lang string) string {
	clean := strings.TrimSpace(name)
	base := strings.ToLower(filepath.Base(clean))
	if base == "" {
		switch strings.ToLower(lang) {
		case "en":
			return "Unknown Process"
		case "de":
			return "Unbekannter Prozess"
		case "ja":
			return "不明なプロセス"
		case "kk":
			return "Белгісіз процесс"
		case "tt":
			return "Билгесез процесс"
		case "zh":
			return "未知进程"
		default:
			return "Неизвестный процесс"
		}
	}

	if item, ok := processDict[base]; ok {
		switch strings.ToLower(lang) {
		case "en":
			if item.En != "" { return item.En }
		case "de":
			if item.De != "" { return item.De }
		case "ja":
			if item.Ja != "" { return item.Ja }
		case "kk":
			if item.Kk != "" { return item.Kk }
		case "tt":
			if item.Tt != "" { return item.Tt }
		case "zh":
			if item.Zh != "" { return item.Zh }
		default:
			if item.Ru != "" { return item.Ru }
		}
		return item.Ru
	}

	// Win32 VersionInfo fallback: if absolute path or resolvable
	if filepath.IsAbs(clean) {
		if desc := getProcessVersionInfo(clean); desc != "" {
			return desc
		}
	}

	// Extension-less fallback
	return strings.TrimSuffix(clean, filepath.Ext(clean))
}
